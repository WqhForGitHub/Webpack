// webpack.config.js
// 演示「exclude node_modules」对打包速度 / 产物体积的影响
//
// 通过 --env scenario=bad|good 切换：
//   - bad ：babel-loader 没写 exclude，会把 node_modules 中的几十 MB
//           源码也跑一遍 babel，慢且没意义。
//   - good：exclude: /node_modules/ + include: src，性能正常。
//
// 实验：
//   npm install
//   npm run build:bad
//   npm run build:good
// 对比终端 webpack 输出的「compiled in xxx ms」。

const path = require("path");

module.exports = (env = {}) => {
  const scenario = env.scenario || "good";
  const isBad = scenario === "bad";

  return {
    mode: "development",
    entry: "./src/index.js",
    output: {
      path: path.resolve(__dirname, `dist/${scenario}`),
      filename: "bundle.js",
      clean: true,
    },
    module: {
      rules: [
        {
          test: /\.js$/,
          // bad：故意不加 exclude/include
          // good：使用 include + exclude 双保险
          ...(isBad
            ? {}
            : {
                include: path.resolve(__dirname, "src"),
                exclude: /node_modules/,
              }),
          use: {
            loader: "babel-loader",
            options: {
              presets: [["@babel/preset-env", { targets: "defaults" }]],
            },
          },
        },
      ],
    },
    stats: {
      timings: true,
      modulesSpace: 30,
    },
  };
};
